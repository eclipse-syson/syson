/**
 * Checks target filtering on connector actions generated by the standard diagram providers.
 *
 * @author mcharfadi
 */
public class SDVConnectorPaletteTests {

    @Test
    public void flowActionsKeepTheirBorderAndInheritedTargetRestrictions() {
        var view = new ViewBuilder().build();
        var diagram = (DiagramDescription) new SDVDiagramDescriptionProvider().create(new ColorProvider(view));
        view.getDescriptions().add(diagram);
        var descriptions = EMFUtils.allContainedObjectOfType(diagram, NodeDescription.class).toList();
        var editingContext = mock(IEditingContext.class);
        var searchService = mock(IViewDiagramDescriptionSearchService.class);
        var queryService = new DiagramQueryElementService(mock(IObjectSearchService.class), searchService, mock(IDiagramIdProvider.class),
                mock(IFeedbackMessageService.class), mock(IDiagramQueryService.class), mock(ModelQueryElementService.class));
        var interpreter = new AQLInterpreter(List.of(), List.of(queryService), List.of());
        var names = new SDVDescriptionNameGenerator();
        var expectedTargets = List.of(
                names.getBorderNodeName(SysmlPackage.eINSTANCE.getPortUsage(), SysmlPackage.eINSTANCE.getUsage_NestedPort()),
                names.getBorderNodeName(SysmlPackage.eINSTANCE.getPortUsage(), SysmlPackage.eINSTANCE.getDefinition_OwnedPort()),
                names.getInheritedBorderNodeName(SysmlPackage.eINSTANCE.getPortUsage(), SysmlPackage.eINSTANCE.getUsage_NestedPort()),
                names.getInheritedBorderNodeName(SysmlPackage.eINSTANCE.getPortUsage(), SysmlPackage.eINSTANCE.getDefinition_OwnedPort()),
                names.getBorderNodeName(SysmlPackage.eINSTANCE.getItemUsage(), SysmlPackage.eINSTANCE.getUsage_NestedItem()),
                names.getBorderNodeName(SysmlPackage.eINSTANCE.getItemUsage(), SysmlPackage.eINSTANCE.getDefinition_OwnedItem()),
                names.getInheritedBorderNodeName(SysmlPackage.eINSTANCE.getItemUsage(), SysmlPackage.eINSTANCE.getUsage_NestedItem()),
                names.getInheritedBorderNodeName(SysmlPackage.eINSTANCE.getItemUsage(), SysmlPackage.eINSTANCE.getDefinition_OwnedItem()),
                names.getBorderNodeName(SysmlPackage.eINSTANCE.getReferenceUsage()),
                names.getInheritedBorderNodeName(SysmlPackage.eINSTANCE.getReferenceUsage()));

        for (var description : descriptions) {
            when(searchService.findViewNodeDescriptionById(editingContext, description.getName())).thenReturn(Optional.of(description));
        }
        for (var sourceName : expectedTargets) {
            var source = descriptions.stream().filter(description -> sourceName.equals(description.getName())).findFirst().orElseThrow();
            assertThat(source.getEdgeTools()).as("Connector palette of %s", sourceName).hasSize(1);
            var flowAction = source.getEdgeTools().getFirst().getPalette().getNodeTools().stream()
                    .filter(action -> "New Flow (flow)".equals(action.getName())).findFirst().orElseThrow();
            for (var description : descriptions) {
                var target = mock(Node.class);
                when(target.getDescriptionId()).thenReturn(description.getName());
                var result = interpreter.evaluateExpression(Map.of("edgeTarget", target, "editingContext", editingContext), flowAction.getPreconditionExpression());
                assertThat(result.asBoolean()).as("Flow from %s to %s", sourceName, description.getName())
                        .contains(expectedTargets.contains(description.getName()));
            }
        }
    }
}
